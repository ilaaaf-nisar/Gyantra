import os
import numpy as np
import tiktoken
import torch
from model import DEFAULT_BLOCK_SIZE, DecoderLLM

# 1. Require a GPU for training instead of silently falling back to CPU.
if torch.cuda.is_available():
    device = torch.device("cuda")
elif torch.backends.mps.is_available():
    device = torch.device("mps")
else:
    raise RuntimeError(
        "GPU training is unavailable. Install a GPU-enabled PyTorch build "
        "and ensure your GPU drivers are installed."
    )

device_name = torch.cuda.get_device_name(device) if device.type == "cuda" else "Apple GPU"
print(f"Using device: {device} ({device_name})")

# 2. Tokenizer setup
enc = tiktoken.get_encoding("gpt2")
BLOCK_SIZE = DEFAULT_BLOCK_SIZE
BATCH_SIZE = 4

# 3. Load pre-tokenized binary datasets (generated by tokenizer.py)
train_bin_path = "data/train.bin"
val_bin_path = "data/val.bin"

if not os.path.exists(train_bin_path) or not os.path.exists(val_bin_path):
    raise FileNotFoundError(
        f"Could not find {train_bin_path} or {val_bin_path}. "
        "Please run tokenizer.py first to generate the binary datasets."
    )

train_data = np.memmap(train_bin_path, dtype=np.uint16, mode="r")
val_data = np.memmap(val_bin_path, dtype=np.uint16, mode="r")

def get_batch(split, batch_size=BATCH_SIZE, block_size=BLOCK_SIZE, device="cpu"):
    """Loads a random chunk of sequences and their next-token targets."""
    data = train_data if split == "train" else val_data
    ix = torch.randint(len(data) - block_size, (batch_size,))
    x = torch.stack([torch.from_numpy(data[i : i + block_size].astype(np.int64)) for i in ix])
    y = torch.stack([torch.from_numpy(data[i + 1 : i + 1 + block_size].astype(np.int64)) for i in ix])
    return x.to(device), y.to(device)

# 4. Model & Optimizer initialization
model = DecoderLLM(
    vocab_size=enc.n_vocab, 
    n_embd=256, 
    n_head=4, 
    n_layer=4, 
    block_size=BLOCK_SIZE
).to(device)

optimizer = torch.optim.AdamW(model.parameters(), lr=3e-4)

# 5. Validation and Evaluation helper
@torch.no_grad()
def estimate_loss(eval_iters=50):
    """Averages losses over multiple batches without tracking gradients."""
    out = {}
    model.eval()  # Disables dropout during evaluation
    for split in ['train', 'val']:
        losses = torch.zeros(eval_iters)
        for k in range(eval_iters):
            x, y = get_batch(split, batch_size=BATCH_SIZE, block_size=BLOCK_SIZE, device=device)
            _, loss = model(x, y)
            losses[k] = loss.item()
        out[split] = losses.mean().item()
    model.train()  # Re-enables dropout for training
    return out

# 6. Pretraining loop
print("Starting pretraining loop...")
model.train()

for step in range(2000):
    # Periodically evaluate train and validation loss
    if step % 250 == 0 or step == 1999:
        losses = estimate_loss(eval_iters=50)
        print(f"Step {step:4d} | Train Loss: {losses['train']:.4f} | Val Loss: {losses['val']:.4f}")

    xb, yb = get_batch("train", batch_size=BATCH_SIZE, block_size=BLOCK_SIZE, device=device)
    logits, loss = model(xb, yb)
    
    optimizer.zero_grad(set_to_none=True)
    loss.backward()
    optimizer.step()

# 7. Save trained model checkpoint
os.makedirs("checkpoints", exist_ok=True)
checkpoint_path = "checkpoints/ignou_llm_final.pt"
torch.save(model.state_dict(), checkpoint_path)
print(f"\nModel weights saved to {checkpoint_path}")

# 8. Generation test
print("\n--- Model Output Test ---")
model.eval()
prompt = "Introduction to"
context = torch.tensor([enc.encode(prompt)], dtype=torch.long, device=device)
out = model.generate(context, max_new_tokens=3000, temperature=0.7)
print(enc.decode(out[0].tolist()))